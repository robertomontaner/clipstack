import AppKit
import Combine
import CryptoKit

@MainActor
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()
    static let limits = [5, 10, 15, 20]

    @Published private(set) var items: [ClipItem] = []
    @Published var paused = false

    /// Cuántos elementos se guardan (5, 10, 15 o 20).
    @Published var limit: Int {
        didSet {
            UserDefaults.standard.set(limit, forKey: "limit")
            trim()
            save()
        }
    }

    /// Atajo global del selector rápido (libre, grabado por el usuario).
    @Published var shortcut: Shortcut {
        didSet {
            if let d = try? JSONEncoder().encode(shortcut) {
                UserDefaults.standard.set(d, forKey: "shortcutV3")
            }
        }
    }

    /// Mientras se graba un atajo nuevo, el atajo actual se desactiva.
    @Published var isRecordingShortcut = false

    private let pb = NSPasteboard.general
    private var lastChange: Int
    private var timer: Timer?
    private let imagesDir: URL
    private let indexURL: URL
    private let thumbs = NSCache<NSString, NSImage>()

    /// Tipos que marcan contenido sensible (gestores de contraseñas, etc.). Se ignoran.
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword"
    ]

    private init() {
        let stored = UserDefaults.standard.integer(forKey: "limit")
        limit = ClipboardStore.limits.contains(stored) ? stored : 10
        if let d = UserDefaults.standard.data(forKey: "shortcutV3"),
           let s = try? JSONDecoder().decode(Shortcut.self, from: d) {
            shortcut = s
        } else {
            shortcut = Shortcut.default
        }

        let base = FileManager.default
            .urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("ClipStack", isDirectory: true)
        imagesDir = base.appendingPathComponent("images", isDirectory: true)
        indexURL = base.appendingPathComponent("history.json")
        try? FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true)

        lastChange = NSPasteboard.general.changeCount
        load()
    }

    // MARK: - Vigilancia del portapapeles

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in self?.poll() }
        }
        if let timer { RunLoop.main.add(timer, forMode: .common) }
    }

    private func poll() {
        let c = pb.changeCount
        guard c != lastChange else { return }
        lastChange = c
        guard !paused else { return }

        let types = pb.types ?? []
        if types.contains(where: { ignoredTypes.contains($0.rawValue) }) { return }

        if let s = pb.string(forType: .string),
           !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            add(text: s)
        } else if let png = currentImagePNG() {
            add(imagePNG: png)
        }
    }

    private func currentImagePNG() -> Data? {
        if let d = pb.data(forType: .png) { return d }
        if let t = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: t) {
            return rep.representation(using: .png, properties: [:])
        }
        return nil
    }

    // MARK: - Alta, baja y orden

    private func add(text: String) {
        insert(ClipItem(kind: .text, text: text, imageFile: nil,
                        hash: Self.sha(Data(text.utf8)), date: Date()))
    }

    private func add(imagePNG: Data) {
        let h = Self.sha(imagePNG)
        if let idx = items.firstIndex(where: { $0.hash == h }) { bump(idx); return }
        let name = UUID().uuidString + ".png"
        do { try imagePNG.write(to: imagesDir.appendingPathComponent(name)) } catch { return }
        insert(ClipItem(kind: .image, text: nil, imageFile: name, hash: h, date: Date()))
    }

    private func insert(_ item: ClipItem) {
        if let idx = items.firstIndex(where: { $0.hash == item.hash }) { bump(idx); return }
        items.insert(item, at: 0)
        trim()
        save()
    }

    private func bump(_ idx: Int) {
        guard idx != 0 else { return }
        var it = items.remove(at: idx)
        it.date = Date()
        items.insert(it, at: 0)
        save()
    }

    private func trim() {
        while items.count > limit {
            deleteFile(items.removeLast())
        }
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        deleteFile(item)
        save()
    }

    func clear() {
        for it in items { deleteFile(it) }
        items = []
        save()
    }

    // MARK: - Uso de un elemento

    /// Pone el elemento en el portapapeles del sistema y lo sube al primer puesto.
    func copyToPasteboard(_ item: ClipItem) {
        pb.clearContents()
        switch item.kind {
        case .text:
            pb.setString(item.text ?? "", forType: .string)
        case .image:
            if let f = item.imageFile,
               let img = NSImage(contentsOf: imagesDir.appendingPathComponent(f)) {
                pb.writeObjects([img])
            }
        }
        lastChange = pb.changeCount   // para que no se registre como copia nueva
        if let idx = items.firstIndex(where: { $0.id == item.id }) { bump(idx) }
    }

    func thumbnail(for item: ClipItem) -> NSImage? {
        guard let f = item.imageFile else { return nil }
        if let c = thumbs.object(forKey: f as NSString) { return c }
        guard let img = NSImage(contentsOf: imagesDir.appendingPathComponent(f)) else { return nil }
        thumbs.setObject(img, forKey: f as NSString)
        return img
    }

    // MARK: - Persistencia

    private func deleteFile(_ item: ClipItem) {
        guard let f = item.imageFile else { return }
        try? FileManager.default.removeItem(at: imagesDir.appendingPathComponent(f))
        thumbs.removeObject(forKey: f as NSString)
    }

    private func save() {
        if let d = try? JSONEncoder().encode(items) {
            try? d.write(to: indexURL, options: .atomic)
        }
    }

    private func load() {
        guard let d = try? Data(contentsOf: indexURL),
              let arr = try? JSONDecoder().decode([ClipItem].self, from: d) else { return }
        items = arr.filter { it in
            if it.kind == .text { return true }
            guard let f = it.imageFile else { return false }
            return FileManager.default.fileExists(atPath: imagesDir.appendingPathComponent(f).path)
        }
        trim()
    }

    private static func sha(_ d: Data) -> String {
        SHA256.hash(data: d).map { String(format: "%02x", $0) }.joined()
    }
}
